/**
 * ensure-bundles.mjs — post-process dist tarballs so every catalog plugin
 * becomes a self-referencing dsh bundle.
 *
 * Why: the kernel's installBundle only LAYERS packages that declare
 * `dsh.bundle.patch`; a package without one is installed as a plain
 * dependency and the manifest is restored ("downloaded files can stay"),
 * so the plugin never composes. The established community pattern (see
 * dsh-our-free-model) is a bundle whose patch inserts its own row. This
 * script adds that to every plugin missing it, in place, and refreshes
 * SHA256SUMS + index.json.
 *
 * Idempotent: tarballs that already declare dsh.bundle are left untouched.
 */
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const DIST = path.join(ROOT, 'dist')
const STAGE = path.join(ROOT, '.cache', 'ensure-stage')

const index = JSON.parse(fs.readFileSync(path.join(DIST, 'index.json'), 'utf8'))

function readManifest(dir) {
  return JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
}

function writeManifest(dir, pkg) {
  fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify(pkg, null, 2) + '\n')
}

function untar(file, destDir) {
  // Relative filenames only: GNU tar misreads `D:/...` as a remote host.
  fs.rmSync(destDir, { recursive: true, force: true })
  fs.mkdirSync(destDir, { recursive: true })
  execFileSync('tar', ['-xzf', path.basename(file), '-C', path.relative(DIST, destDir)], { cwd: DIST, stdio: 'pipe' })
}

function pack(dir, outFile) {
  fs.rmSync(outFile, { force: true })
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  // npm renames scoped packages to dash-form filenames; ask --json for the
  // actual filename so the result always lands on the canonical path.
  const out = execFileSync('npm', ['pack', dir, '--json', '--pack-destination', path.dirname(outFile)], { stdio: 'pipe', shell: true, encoding: 'utf8' })
  const packed = JSON.parse(out)[0]?.filename
  if (!packed) throw new Error('npm pack produced no filename')
  const from = path.join(path.dirname(outFile), packed)
  if (path.resolve(from) !== path.resolve(outFile)) fs.copyFileSync(from, outFile)
}

let changed = 0
let untouched = 0

for (const entry of index) {
  const tgz = path.join(DIST, entry.file)
  if (!fs.existsSync(tgz)) {
    console.error(`[ensure] missing ${entry.file}, skip`)
    continue
  }
  // unpack
  const dir = path.join(STAGE, entry.name)
  untar(tgz, dir)
  const pkgDir = path.join(dir, 'package')
  const pkg = readManifest(pkgDir)

  if (pkg.dsh?.bundle?.patch) {
    untouched++
    continue
  }

  const id = entry.id
  const patchFile = './cordis.patch.yml'
  const patch = [
    `# ${pkg.name} self-mount bundle patch (generated by dsh-plugin-suite repack pipeline).`,
    '# One insert mounts the plugin with default config; the row name points at this',
    "# package itself, so installing the bundle composes the plugin.",
    '- insert:',
    `    - id: ${id}`,
    `      name: '${pkg.name}'`,
    '      config: {}',
    '',
  ].join('\n')
  fs.writeFileSync(path.join(pkgDir, 'cordis.patch.yml'), patch)
  pkg.dsh = { ...(pkg.dsh ?? {}), bundle: { patch: patchFile } }
  if (Array.isArray(pkg.files) && !pkg.files.some((f) => f.replace(/^\.\//, '') === 'cordis.patch.yml')) {
    pkg.files.push('cordis.patch.yml')
  }
  writeManifest(pkgDir, pkg)

  const packed = path.join(path.dirname(tgz), `${pkg.name}-${pkg.version}.tgz`)
  pack(pkgDir, packed)
  // npm pack names it <name>-<version>.tgz already — move over the original name if needed
  if (path.resolve(packed) !== path.resolve(tgz) && fs.existsSync(packed)) fs.copyFileSync(packed, tgz)

  const bytes = fs.statSync(tgz).size
  entry.sha256 = crypto.createHash('sha256').update(fs.readFileSync(tgz)).digest('hex')
  entry.bytes = bytes
  changed++
  console.log(`[ensure] bundled ${entry.name}@${entry.version}`)
}

fs.writeFileSync(path.join(DIST, 'index.json'), JSON.stringify(index, null, 2) + '\n')

// refresh SHA256SUMS
const sums = index
  .map((e) => `${e.sha256}  ${e.file}`)
  .join('\n')
fs.writeFileSync(path.join(DIST, 'SHA256SUMS'), sums + '\n')

console.log(`[ensure] done: ${changed} bundled, ${untouched} already bundles`)
